"""Regenerate the USB HID map: python3 example/tool/generate_physical_keys.py FLUTTER_SDK."""
import json
from pathlib import Path
import re
import sys


def main():
    root = Path(__file__).resolve().parents[2]
    sdk = Path(sys.argv[1])
    source = (sdk / 'packages/flutter/lib/src/services/keyboard_key.g.dart').read_text()
    source = source[source.index('class PhysicalKeyboardKey'):]
    usages = dict(re.findall(
        r'static const PhysicalKeyboardKey (\w+) = PhysicalKeyboardKey\((0x[0-9a-f]+)\)',
        source,
    ))
    codes = json.loads((root / 'conformance/fixtures/constants.json').read_text())['code_map']
    lines = [
        '// Copyright 2026 Mobilerun',
        '// SPDX-License-Identifier: Apache-2.0',
        '',
        '// Internal input implementation; not exported by the package.',
        '// ignore_for_file: public_member_api_docs',
        '',
        '// GENERATED by example/tool/generate_physical_keys.py with a Flutter SDK.',
        '// USB HID usages from Flutter PhysicalKeyboardKey, paired with the W3C',
        '// code_map in conformance/fixtures/constants.json. No debug names at runtime.',
        'const physicalKeyCodes = <int, String>{',
    ]
    for code in codes:
        name = code[0].lower() + code[1:]
        lines.append(f"  {usages[name]}: '{code}',")
    lines.extend(['};', ''])
    (root / 'lib/src/core/input/physical_key_codes.dart').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
