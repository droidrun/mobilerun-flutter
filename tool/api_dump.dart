import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:analyzer/dart/element/element.dart';

/// Generates the public contract exported by the package entry point.
Future<void> main(List<String> arguments) async {
  if (arguments.isNotEmpty &&
      (arguments.length != 1 || arguments.single != '--check')) {
    stderr.writeln('Usage: dart run tool/api_dump.dart [--check]');
    exitCode = 64;
    return;
  }
  final root = Directory.current.absolute.path;
  final entry = '$root/lib/mobilerun_flutter.dart';
  final contexts = AnalysisContextCollection(includedPaths: [entry]);
  try {
    final result = await contexts
        .contextFor(entry)
        .currentSession
        .getLibraryByUri(Uri.file(entry).toString());
    if (result is! LibraryElementResult) {
      throw StateError('Cannot resolve the public entry point: $result');
    }
    final exports = result.element.exportNamespace.definedNames2;
    final names = exports.keys.toList()..sort();
    final output = StringBuffer(
      '// Generated by tool/api_dump.dart; do not edit.\n'
      '// Public exports and declared public member signatures.\n\n',
    );
    for (final name in names) {
      final element = exports[name]!;
      output.writeln(_signature(element));
      if (element is InterfaceElement) {
        final members = <String>{};
        // Include members inherited from package types, even if the superclass
        // itself is hidden by the entry point's show combinators.
        final types = [
          element,
          ...element.allSupertypes
              .where(
                (type) =>
                    type.element.library.uri.scheme == 'package' &&
                    type.element.library.uri.path.startsWith(
                      'mobilerun_flutter/',
                    ),
              )
              .map((type) => type.element),
        ];
        for (final type in types) {
          final declarations = <Element>[
            if (type == element) ...type.constructors,
            ...type.fields.where((field) => !field.isOriginGetterSetter),
            ...type.getters.where((getter) => !getter.isOriginVariable),
            ...type.setters.where((setter) => !setter.isOriginVariable),
            ...type.methods,
          ];
          for (final member in declarations.where(
            (member) => member.isPublic,
          )) {
            members.add(_signature(member));
          }
        }
        for (final member in members.toList()..sort()) {
          output.writeln('  $member');
        }
      }
      output.writeln();
    }
    final baseline = File('$root/api/mobilerun_flutter.api.txt');
    if (arguments.contains('--check')) {
      if (!baseline.existsSync() || baseline.readAsStringSync() != '$output') {
        stderr.writeln(
          'Public API changed. Run dart run tool/api_dump.dart and review the diff.',
        );
        exitCode = 1;
      } else {
        stdout.writeln('Public API matches the committed baseline.');
      }
    } else {
      baseline.parent.createSync(recursive: true);
      baseline.writeAsStringSync('$output');
      stdout.writeln('Updated api/mobilerun_flutter.api.txt');
    }
  } finally {
    await contexts.dispose();
  }
}

String _signature(Element element) {
  final modifiers = <String>[];
  if (element is ConstructorElement) {
    if (element.isConst) modifiers.add('const');
    if (element.isFactory) modifiers.add('factory');
  } else if (element is ExecutableElement) {
    if (element.isStatic) modifiers.add('static');
    if (element.isAbstract) modifiers.add('abstract');
  } else if (element is VariableElement) {
    if (element.isStatic) modifiers.add('static');
    if (element.isConst) modifiers.add('const');
    if (element.isFinal) modifiers.add('final');
    if (element.isLate) modifiers.add('late');
  }
  final declaration = element.displayString(preferTypeAlias: true);
  return [...modifiers, declaration].join(' ');
}
