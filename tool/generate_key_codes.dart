// Run from the repository root: dart tool/generate_key_codes.dart FLUTTER_SDK
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final source = File(
    '${args.single}/packages/flutter/lib/src/services/keyboard_key.g.dart',
  ).readAsStringSync();
  final codes =
      (jsonDecode(
                File('conformance/fixtures/constants.json').readAsStringSync(),
              )
              as Map)['code_map']
          as Map;
  final output = StringBuffer('''// Copyright 2026 Mobilerun
// SPDX-License-Identifier: Apache-2.0

// Internal input implementation; not exported by the package.
// ignore_for_file: public_member_api_docs

// GENERATED by tool/generate_key_codes.dart with a Flutter SDK.
// Flutter key identifiers paired with the W3C fixture code_map.
''');
  for (final kind in ['Physical', 'Logical']) {
    final entries = {
      for (final match in RegExp(
        'static const ${kind}KeyboardKey (\\w+) = '
        '${kind}KeyboardKey\\((0x[0-9a-f]+)\\)',
      ).allMatches(source))
        match[1]!: match[2]!,
    };
    output.writeln('const ${kind.toLowerCase()}KeyCodes = <int, String>{');
    for (final code in codes.keys.cast<String>()) {
      final name = '${code[0].toLowerCase()}${code.substring(1)}';
      final identifier = entries[name];
      if (identifier == null) throw StateError('No $kind key for $code');
      output.writeln("  $identifier: '$code',");
    }
    output.writeln('};');
  }
  File(
    'lib/src/core/input/physical_key_codes.dart',
  ).writeAsStringSync(output.toString());
}
